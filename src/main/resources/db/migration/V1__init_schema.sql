-- Kullanicilar
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('USER', 'ADMIN')),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Kategoriler (Corba, Ana Yemek, Tatli ...)
CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

-- Tarifler: her tarifin bir kategorisi ve bir yazari var
CREATE TABLE recipes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(120) NOT NULL,
    description  VARCHAR(1000),
    instructions TEXT         NOT NULL,
    prep_minutes INTEGER      NOT NULL CHECK (prep_minutes > 0),
    servings     INTEGER      NOT NULL CHECK (servings > 0),
    difficulty   VARCHAR(10)  NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    category_id  BIGINT       NOT NULL REFERENCES categories (id),
    author_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_recipes_category ON recipes (category_id);
CREATE INDEX idx_recipes_author ON recipes (author_id);

-- Malzemeler: tarife bagli, sirali liste. Tarif silinince malzemeleri de silinir.
CREATE TABLE recipe_ingredients (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT       NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    name      VARCHAR(100) NOT NULL,
    quantity  VARCHAR(50)  NOT NULL,
    position  INTEGER      NOT NULL
);
CREATE INDEX idx_ingredients_recipe ON recipe_ingredients (recipe_id);

-- Favoriler: kullanici-tarif eslesmesi. Ayni tarif iki kez favorilenemez (birlesik anahtar).
CREATE TABLE favorites (
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    recipe_id  BIGINT NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, recipe_id)
);

-- Yorumlar ve puanlar: bir kullanici bir tarife en fazla bir yorum yazabilir.
CREATE TABLE reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT  NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    user_id    BIGINT  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating     INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment    VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_reviews_recipe_user UNIQUE (recipe_id, user_id)
);
CREATE INDEX idx_reviews_recipe ON reviews (recipe_id);
